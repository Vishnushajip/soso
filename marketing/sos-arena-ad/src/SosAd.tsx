import { Audio } from "@remotion/media";
import React from "react";
import { AbsoluteFill, interpolate, Sequence, staticFile, useCurrentFrame } from "remotion";
import { lerp } from "./anim";
import { Background } from "./components/Background";
import { Stage } from "./components/Stage";
import "./fonts";
import { Audiences, CARD_LEN } from "./scenes/Audiences";
import { Cta } from "./scenes/Cta";
import { EMOTE_TIMES, FEATURE_LEN, Features } from "./scenes/Features";
import { Gameplay, MOVES } from "./scenes/Gameplay";
import { Hook } from "./scenes/Hook";
import { Versus } from "./scenes/Versus";
import { Victory } from "./scenes/Victory";
import { C, FPS } from "./theme";
import VO_DURATIONS from "../public/vo/durations.json";

const SCENES = [
  { id: "hook", len: 75, C: Hook, tint: C.secondary },
  { id: "gameplay", len: 150, C: Gameplay, tint: C.primary },
  { id: "versus", len: 90, C: Versus, tint: C.arenaPink },
  { id: "audiences", len: 150, C: Audiences, tint: C.arenaBlue },
  { id: "features", len: FEATURE_LEN * 3, C: Features, tint: C.primary },
  { id: "victory", len: 90, C: Victory, tint: C.arenaGold },
  { id: "cta", len: 135, C: Cta, tint: C.primaryContainer },
] as const;

const starts: Record<string, number> = {};
let acc = 0;
for (const s of SCENES) {
  starts[s.id] = acc;
  acc += s.len;
}
export const TOTAL_FRAMES = acc;

// Voiceover: one line per scene, starting a few frames after the cut.
// Generated by voiceover/generate_vo.py (Kokoro TTS).
const VO_LINES = [
  { id: "hook", at: 6 },
  { id: "gameplay", at: starts.gameplay + 8 },
  { id: "versus", at: starts.versus + 10 },
  { id: "audiences", at: starts.audiences + 6 },
  { id: "features", at: starts.features + 4 },
  { id: "victory", at: starts.victory + 8 },
  { id: "cta", at: starts.cta + 10 },
].map((l) => ({ ...l, len: Math.ceil(VO_DURATIONS[l.id as keyof typeof VO_DURATIONS] * FPS) }));

const MUSIC = 0.5;
const DUCKED = 0.16;
// Music bed volume: fades in/out and ducks smoothly under every VO line.
const musicVolume = (f: number) => {
  const env = interpolate(f, [0, 8, TOTAL_FRAMES - 30, TOTAL_FRAMES], [0, 1, 1, 0], { extrapolateLeft: "clamp", extrapolateRight: "clamp" });
  let duck = 0;
  for (const l of VO_LINES) {
    duck = Math.max(duck, interpolate(f, [l.at - 6, l.at, l.at + l.len, l.at + l.len + 8], [0, 1, 1, 0], { extrapolateLeft: "clamp", extrapolateRight: "clamp" }));
  }
  return env * (MUSIC - (MUSIC - DUCKED) * duck);
};

// Punch-in entrance for every cut.
const SceneIn: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const f = useCurrentFrame();
  return (
    <AbsoluteFill style={{ scale: String(lerp(f, [0, 9], [1.12, 1])), filter: `blur(${lerp(f, [0, 7], [12, 0])}px)` }}>
      {children}
    </AbsoluteFill>
  );
};

const Flash: React.FC = () => {
  const f = useCurrentFrame();
  return <AbsoluteFill style={{ background: "white", opacity: lerp(f, [0, 5], [0.55, 0]), pointerEvents: "none" }} />;
};

const Sfx: React.FC<{ at: number; src: string; volume?: number }> = ({ at, src, volume = 0.8 }) => (
  <Sequence from={at} layout="none">
    <Audio src={staticFile(`sfx/${src}.mp3`)} volume={volume} />
  </Sequence>
);

export const SosAd: React.FC = () => {
  const frame = useCurrentFrame();
  const current = [...SCENES].reverse().find((s) => frame >= starts[s.id]) ?? SCENES[0];
  const g = starts.gameplay, a = starts.audiences, ft = starts.features;
  return (
    <AbsoluteFill>
      <Background tint={current.tint} />
      {SCENES.map((s) => (
        <Sequence key={s.id} name={s.id} from={starts[s.id]} durationInFrames={s.len}>
          <Stage>
            <SceneIn>
              <s.C />
            </SceneIn>
          </Stage>
          {s.id !== "hook" && <Flash />}
        </Sequence>
      ))}

      {/* Music bed: the game's own theme */}
      <Audio
        src={staticFile("sfx/theme.mp3")}
        volume={musicVolume}
      />

      {/* Voiceover */}
      {VO_LINES.map((l) => (
        <Sequence key={l.id} name={`vo-${l.id}`} from={l.at} durationInFrames={l.len + 6} layout="none">
          <Audio src={staticFile(`vo/${l.id}.wav`)} volume={1} />
        </Sequence>
      ))}

      {/* Sound design, all from assets/sounds */}
      {[2, 10, 18].map((t) => <Sfx key={t} at={t} src="point" volume={0.9 * 0.7} />)}
      <Sfx at={28} src="sos" volume={0.55} />
      {[MOVES.blueDouble, MOVES.blueSetup, MOVES.pinkDouble].map((t) => <Sfx key={t} at={g + t - 4} src="button_click" volume={0.6 * 0.7} />)}
      <Sfx at={g + MOVES.blueDouble + 3} src="sos" volume={0.55} />
      <Sfx at={g + MOVES.pinkDouble + 3} src="sos" volume={0.55} />
      <Sfx at={starts.versus + 12} src="versus" volume={0.6} />
      {[0, 1, 2, 3].map((i) => <Sfx key={i} at={a + 2 + i * CARD_LEN} src="button_click" volume={0.5 * 0.7} />)}
      {[0, 2, 4].map((i) => <Sfx key={i} at={ft + EMOTE_TIMES[i]} src="notify" volume={0.5 * 0.7} />)}
      {[0, 1, 2, 3, 4].map((i) => <Sfx key={i} at={ft + FEATURE_LEN + i * 11} src="button_click" volume={0.45 * 0.7} />)}
      <Sfx at={ft + FEATURE_LEN * 2 + 4} src="rank_up" volume={0.45} />
      <Sfx at={starts.victory + 4} src="win" volume={0.7} />
      <Sfx at={starts.cta + 2} src="point" volume={0.55} />
      <Sfx at={starts.cta + 22} src="button_click" volume={0.7 * 0.7} />
    </AbsoluteFill>
  );
};
